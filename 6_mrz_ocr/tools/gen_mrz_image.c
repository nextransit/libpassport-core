/* gen_mrz_image -- render a synthetic MRZ band into a PPM image.
 *
 * Usage:
 *   gen_mrz_image <out.ppm> <line1> <line2> [opts]
 *
 * Options (space-separated, key=value):
 *   lines=<1..3>          number of MRZ rows to render (default 2).
 *                         lines=1 with a 30-character <line1> and an
 *                         empty <line2> renders the CS/CD travel-permit
 *                         layout (single row of 30); lines=3 renders a
 *                         TD1 back (three rows of 30).
 *   scale=<int>           glyph scale factor (default 4)
 *   hgap=<int>            horizontal gap between glyphs (default 2)
 *   vgap=<int>            vertical gap between two lines (default 6)
 *   margin=<int>          outer margin (default 12)
 *   noise=<float>         pixel noise probability 0..1 (default 0)
 *   noise-seed=<int>      deterministic noise seed. When given, the
 *                         noise is reproducible for a given corpus
 *                         record (required for regression baselines).
 *                         When omitted, falls back to time^pid.
 *   skew=<int>            tilt the band by -N..N pixels across the row
 *                         (default 0)
 *   rot=<float>           rotate the whole band by degrees (real
 *                         scanner tilt, default 0; range +-8)
 *   illum=<int>           illumination-gradient amplitude 0..200:
 *                         background dims linearly across the image
 *                         (scan shading, default 0)
 *   blur=<0|1|2>          3x3 binomial blur passes (simulates defocus
 *                         / anti-aliased strokes, default 0)
 *   invert=<0|1>          render ink=white-on-black instead of
 *                         black-on-white (default 0)
 *   font=bitmap|ocrb      glyph shapes: "bitmap" (default) uses the
 *                         hand-simplified 8x12 bank in src/template.c,
 *                         "ocrb" uses the real OCR-B TrueType rendering
 *                         in tools/ocrb_glyphs.h (generated by
 *                         tools/gen_ocrb_glyphs.py)
 *
 * The output image is grayscale: white background (255) and black ink
 * (0), unless `invert=1` is passed.
 *
 * The output dimension is computed from the parameters; we don't try
 * to embed the band into a full passport page -- the OCR pipeline
 * expects the band to occupy a significant fraction of the height.
 */
#include "face.h"
#define _DEFAULT_SOURCE
#include "template.h"
#include "ocrb_glyphs.h"
#include "ocrb_glyphs_aa.h"
#include "mrz_phys.h"

#include <stdio.h>
#include <unistd.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <math.h>

static int get_int(const char *name, const char *kv) {
    if (strncmp(kv, name, strlen(name)) != 0) return -1;
    return atoi(kv + strlen(name) + 1);
}
static float get_float(const char *name, const char *kv) {
    if (strncmp(kv, name, strlen(name)) != 0) return -1;
    return (float)atof(kv + strlen(name) + 1);
}

/* 3x3 binomial blur on a single-channel buffer (weights 1-2-1). */
static void blur3(uint8_t *g, int W, int H) {
    uint8_t *out = (uint8_t *)malloc((size_t)W * H);
    if (!out) return;
    static const int w[3][3] = {{1, 2, 1}, {2, 4, 2}, {1, 2, 1}};
    for (int y = 0; y < H; ++y)
        for (int x = 0; x < W; ++x) {
            int acc = 0, wsum = 0;
            for (int dy = -1; dy <= 1; ++dy)
                for (int dx = -1; dx <= 1; ++dx) {
                    int yy = y + dy, xx = x + dx;
                    if (yy < 0 || yy >= H || xx < 0 || xx >= W) continue;
                    acc += g[yy * W + xx] * w[dy + 1][dx + 1];
                    wsum += w[dy + 1][dx + 1];
                }
            out[y * W + x] = (uint8_t)(acc / wsum);
        }
    memcpy(g, out, (size_t)W * H);
    free(out);
}

/* Rotate a single-channel buffer by deg about its center
 * (inverse-map nearest neighbour, background fill). */
static void rotate_gray(uint8_t *g, int W, int H, double deg, uint8_t bg) {
    double rad = deg * M_PI / 180.0;
    double c = cos(rad), s = sin(rad);
    double cx = (W - 1) / 2.0, cy = (H - 1) / 2.0;
    uint8_t *out = (uint8_t *)malloc((size_t)W * H);
    if (!out) return;
    for (int y = 0; y < H; ++y)
        for (int x = 0; x < W; ++x) {
            double dx = x - cx, dy = y - cy;
            double sx = cx + c * dx + s * dy;
            double sy = cy - s * dx + c * dy;
            int ix = (int)lround(sx), iy = (int)lround(sy);
            out[y * W + x] = (ix >= 0 && ix < W && iy >= 0 && iy < H)
                                 ? g[iy * W + ix] : bg;
        }
    memcpy(g, out, (size_t)W * H);
    free(out);
}

static void put_ink(uint8_t *img, int W, int H, int x, int y,
                    int invert, uint8_t v) {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    img[y * W + x] = invert ? (uint8_t)(255 - v) : v;
}

/* Glyph bank selection.  0 = the hand-simplified bitmap bank in
 * src/template.c (historical default, keeps every existing corpus
 * bit-identical); 1 = the real OCR-B rendering in tools/ocrb_glyphs.h. */
static int g_font_ocrb = 0;

/* Anti-aliased strokes.  The glyph bank is one-bit, so a hard raster
 * gives perfectly binary edges -- something a scanned machine-readable
 * zone never has.  With aa=1 every cell is rendered at 2x and box
 * filtered down to the cell grid, so stroke edges carry grey levels
 * (the CNN was trained on grayscale photographs, not on bilevel art). */
static int g_aa = 0;

/* Physical pipeline (outline §4.1 / §4.3).  phys=0 keeps the legacy
 * rendering bit-identical; phys=1 renders with the 8-bit coverage bank
 * and the S1..S8 order. */
static int g_phys = 0;
static int g_ink_min = 20, g_ink_max = 110;
static int g_paper_min = 180, g_paper_max = 245;
static float g_blur_sigma = -1.0f;      /* <0: derive from blur= */
static int g_motion_len = 0;
static float g_motion_deg = 0.0f;
static float g_noise_gauss = 0.0f;
static float g_dark_current = 0.0f;
static float g_downscale = 1.0f;
static int g_jpeg_q = 0;
static float g_guilloche = 0.0f;

static int ocrb_glyph_index(char c) {
    for (int i = 0; i < (int)(sizeof(MRZ_OCRB_GLYPHS) / sizeof(MRZ_OCRB_GLYPHS[0])); ++i)
        if (MRZ_OCRB_GLYPHS[i].ch == c) return i;
    return -1;
}

static void draw_glyph(uint8_t *img, int W, int H, int ox, int oy,
                       char c, int scale, int invert) {
    int ink_bit[MRZ_OCR_GLYPH_H][MRZ_OCR_GLYPH_W];
    if (g_font_ocrb) {
        int oi = ocrb_glyph_index(c);
        if (oi < 0) oi = ocrb_glyph_index('<');
        const mrz_ocr_ocrb_glyph_t *og = &MRZ_OCRB_GLYPHS[oi];
        for (int y = 0; y < MRZ_OCR_GLYPH_H; ++y)
            for (int x = 0; x < MRZ_OCR_GLYPH_W; ++x)
                ink_bit[y][x] = (og->rows[y] >> (7 - x)) & 1;
    } else {
        int gi = mrz_ocr_glyph_index(c);
        if (gi < 0) gi = mrz_ocr_glyph_index('<');
        const mrz_ocr_glyph_t *g = &MRZ_OCR_GLYPHS[gi];
        for (int y = 0; y < MRZ_OCR_GLYPH_H; ++y)
            for (int x = 0; x < MRZ_OCR_GLYPH_W; ++x)
                ink_bit[y][x] = (g->rows[y] >> (7 - x)) & 1;
    }
    if (!g_aa) {
        for (int y = 0; y < MRZ_OCR_GLYPH_H; ++y)
            for (int x = 0; x < MRZ_OCR_GLYPH_W; ++x) {
                if (!ink_bit[y][x]) continue;
                for (int dy = 0; dy < scale; ++dy)
                    for (int dx = 0; dx < scale; ++dx)
                        put_ink(img, W, H,
                                ox + x * scale + dx,
                                oy + y * scale + dy,
                                invert, 0);
            }
        return;
    }
    /* AA: draw the cell blocky into a local buffer, low-pass it so the
     * stroke edges turn into a grey fringe, then blend that coverage into
     * the band.  A one-bit bank cannot be anti-aliased by subdivision
     * (the source grid is preserved), so the fringe has to come from a
     * filter -- which is exactly what a camera sees on a printed MRZ. */
    int gw = MRZ_OCR_GLYPH_W * scale, gh = MRZ_OCR_GLYPH_H * scale;
    uint8_t *cell = (uint8_t *)malloc((size_t)gw * gh);
    if (!cell) return;
    memset(cell, 255, (size_t)gw * gh);
    for (int y = 0; y < MRZ_OCR_GLYPH_H; ++y)
        for (int x = 0; x < MRZ_OCR_GLYPH_W; ++x) {
            if (!ink_bit[y][x]) continue;
            for (int dy = 0; dy < scale; ++dy)
                for (int dx = 0; dx < scale; ++dx)
                    cell[(y * scale + dy) * gw + (x * scale + dx)] = 0;
        }
    blur3(cell, gw, gh);
    int ink_target = invert ? 255 : 0;
    for (int y = 0; y < gh; ++y)
        for (int x = 0; x < gw; ++x) {
            int cov = 255 - cell[y * gw + x];   /* 0 = paper, 255 = full ink */
            if (cov <= 0) continue;
            int px = ox + x, py = oy + y;
            if (px < 0 || py < 0 || px >= W || py >= H) continue;
            uint8_t old = img[py * W + px];
            img[py * W + px] = (uint8_t)(old + ((ink_target - (int)old) * cov) / 255);
        }
    free(cell);
}

int main(int argc, char **argv) {
    if (argc < 4) {
        fprintf(stderr, "usage: %s <out.ppm> <line1> <line2> [opts...]\n",
                argv[0]);
        return 2;
    }
    const char *out = argv[1];
    const char *l1 = argv[2];
    const char *l2 = argv[3];
    int scale = 4, hgap = 2, vgap = 6, margin = 12, skew = 0, invert = 0;
    int noise_seed = -1, illum = 0, blur = 0;
    /* lines=1 renders a single MRZ row -- the CS/CD travel-permit layout
     * (1 x 30 characters).  Default stays 2 so every corpus rendered
     * before this option existed is bit-identical. */
    int n_lines = 2;
    float noise = 0, rot = 0;
    for (int i = 4; i < argc; ++i) {
        int v;
        float f;
        /* NOTE: every branch must first match its KEY. A bare
         * "get_int(name, kv) >= lo && <= hi" range test also matches
         * the -1 sentinel of ANY other key and swallows the rest of
         * the chain (the historical bug that silently disabled
         * noise/invert/... in every corpus rendered before 2026-09). */
        if (strncmp(argv[i], "lines", 5) == 0 && (v = get_int("lines", argv[i])) >= 1 && v <= 3) n_lines = v;
        else if (strncmp(argv[i], "scale", 5) == 0 && (v = get_int("scale", argv[i])) >= 0) scale = v;
        else if (strncmp(argv[i], "hgap", 4) == 0 && (v = get_int("hgap", argv[i])) >= 0) hgap = v;
        else if (strncmp(argv[i], "vgap", 4) == 0 && (v = get_int("vgap", argv[i])) >= 0) vgap = v;
        else if (strncmp(argv[i], "margin", 6) == 0 && (v = get_int("margin", argv[i])) >= 0) margin = v;
        else if (strncmp(argv[i], "skew", 4) == 0 && (v = get_int("skew", argv[i])) >= -1000 && v <= 1000) skew = v;
        else if (strncmp(argv[i], "invert", 6) == 0 && (v = get_int("invert", argv[i])) >= 0) invert = v;
        else if (strncmp(argv[i], "noise-seed", 10) == 0 && (v = get_int("noise-seed", argv[i])) >= 0) noise_seed = v;
        else if (strncmp(argv[i], "illum", 5) == 0 && (v = get_int("illum", argv[i])) >= 0) illum = v;
        else if (strncmp(argv[i], "blur", 4) == 0 && (v = get_int("blur", argv[i])) >= 0) blur = v;
        else if (strncmp(argv[i], "noise", 5) == 0 && (f = get_float("noise", argv[i])) >= 0) noise = f;
        else if (strncmp(argv[i], "rot", 3) == 0 && (f = get_float("rot", argv[i])) >= -8.0f && f <= 8.0f) rot = f;
        else if (strncmp(argv[i], "font", 4) == 0 && strcmp(argv[i] + 5, "ocrb") == 0) g_font_ocrb = 1;
        else if (strncmp(argv[i], "aa", 2) == 0 && (v = get_int("aa", argv[i])) >= 0) g_aa = v ? 1 : 0;
        else if (strncmp(argv[i], "phys", 4) == 0 && (v = get_int("phys", argv[i])) >= 0) g_phys = v ? 1 : 0;
        else if (strncmp(argv[i], "ink-min", 7) == 0 && (v = get_int("ink-min", argv[i])) >= 0) g_ink_min = v;
        else if (strncmp(argv[i], "ink-max", 7) == 0 && (v = get_int("ink-max", argv[i])) >= 0) g_ink_max = v;
        else if (strncmp(argv[i], "paper-min", 9) == 0 && (v = get_int("paper-min", argv[i])) >= 0) g_paper_min = v;
        else if (strncmp(argv[i], "paper-max", 9) == 0 && (v = get_int("paper-max", argv[i])) >= 0) g_paper_max = v;
        else if (strncmp(argv[i], "blur-sigma", 10) == 0) g_blur_sigma = get_float("blur-sigma", argv[i]);
        else if (strncmp(argv[i], "motion-len", 10) == 0 && (v = get_int("motion-len", argv[i])) >= 0) g_motion_len = v;
        else if (strncmp(argv[i], "motion-deg", 10) == 0) g_motion_deg = get_float("motion-deg", argv[i]);
        else if (strncmp(argv[i], "noise-gauss", 11) == 0) g_noise_gauss = get_float("noise-gauss", argv[i]);
        else if (strncmp(argv[i], "dark-current", 12) == 0) g_dark_current = get_float("dark-current", argv[i]);
        else if (strncmp(argv[i], "downscale", 9) == 0) g_downscale = get_float("downscale", argv[i]);
        else if (strncmp(argv[i], "jpeg", 4) == 0 && (v = get_int("jpeg", argv[i])) >= 0) g_jpeg_q = v;
        else if (strncmp(argv[i], "guilloche", 9) == 0) g_guilloche = get_float("guilloche", argv[i]);
    }
    int n1 = (int)strlen(l1);
    int n2 = (int)strlen(l2);
    int n = n1 > n2 ? n1 : n2;
    int glyph_w = MRZ_OCR_GLYPH_W * scale;
    int glyph_h = MRZ_OCR_GLYPH_H * scale;
    int line_w = n * glyph_w + (n - 1) * hgap;
    int band_w = line_w + margin * 2;
    int line_h = glyph_h;
    int band_h = line_h * n_lines + vgap * (n_lines - 1) + margin * 2;
    if (skew < 0) skew = -skew;

    face_image_t *img = face_image_new(band_w, band_h);
    if (!img) return 2;
    /* Build a 1-channel scratch buffer of the band so we can add noise
     * to the ink properly. Background carries an illumination gradient
     * (scan shading): brightest at top-left, dims by `illum` toward the
     * bottom-right corner. */
    uint8_t *gray = (uint8_t *)malloc((size_t)band_w * band_h);
    if (!gray) { face_image_free(img); return 2; }
    uint8_t bg = invert ? 0 : 255;
    for (int y = 0; y < band_h; ++y)
        for (int x = 0; x < band_w; ++x) {
            float t = 0.5f * (float)x / (float)band_w
                    + 0.5f * (float)y / (float)band_h;
            int v = (int)((float)bg - (float)illum * t);
            if (v < 0) v = 0;
            if (v > 255) v = 255;
            gray[y * band_w + x] = (uint8_t)v;
        }

    if (g_phys) {
        /* ---------- physical pipeline (outline §4.1 / §4.3) ---------- */
        uint32_t seed = (uint32_t)(noise_seed >= 0 ? noise_seed : 12345u);
        mrz_phys_srand(seed ? seed : 1u);
        int paper = g_paper_min + (int)(mrz_phys_randf() *
                                        (float)(g_paper_max - g_paper_min));
        if (paper > 255) paper = 255;
        memset(gray, (uint8_t)paper, (size_t)band_w * band_h);

        /* S2: slow ink-density field (per-stroke unevenness). */
        float *field = (float *)malloc(sizeof(float) * (size_t)band_w * band_h);
        if (field) {
            float cx = mrz_phys_randf() * (float)band_w;
            float cy = mrz_phys_randf() * (float)band_h;
            for (int y = 0; y < band_h; ++y)
                for (int x = 0; x < band_w; ++x) {
                    float dx = (float)x - cx, dy = (float)y - cy;
                    float d2 = (dx * dx + dy * dy) / 900.0f;
                    field[y * band_w + x] = 1.0f - 0.15f * expf(-d2)
                                         + 0.05f * mrz_phys_gauss();
                    if (field[y * band_w + x] < 0.5f)
                        field[y * band_w + x] = 0.5f;
                    if (field[y * band_w + x] > 1.15f)
                        field[y * band_w + x] = 1.15f;
                }
        }

        /* S1: antialiased grey glyphs with a real ink colour. */
        for (int li = 0; li < n_lines; ++li) {
            const char *line = (li == 0) ? l1 : l2;
            int len = (int)strlen(line);
            int row_y = margin + li * (line_h + vgap);
            int row_x_start = margin;
            for (int i = 0; i < len; ++i) {
                int skew_dx = skew * i / len;
                int x = row_x_start + i * (glyph_w + hgap) + skew_dx;
                int ink = g_ink_min + (int)(mrz_phys_randf() *
                                            (float)(g_ink_max - g_ink_min));
                mrz_phys_draw_glyph(gray, band_w, band_h, x, row_y, line[i],
                                    scale, ink, field);
            }
        }
        free(field);

        /* S3: guilloche background. */
        if (g_guilloche > 0.0f)
            mrz_phys_guilloche(gray, band_w, band_h, g_guilloche);

        /* S4: light field + 2D highlight (clipped). */
        {
            float hl_peak = 0.0f, hl_sx = 0.25f, hl_sy = 0.2f;
            float hl_cx = 0.5f, hl_cy = 0.5f;
            if (mrz_phys_randf() < 0.35f) {
                hl_peak = 1.2f + 0.8f * mrz_phys_randf();
                hl_sx = 0.1f + 0.3f * mrz_phys_randf();
                hl_sy = 0.1f + 0.3f * mrz_phys_randf();
                hl_cx = mrz_phys_randf();
                hl_cy = mrz_phys_randf();
            }
            mrz_phys_light_field(gray, band_w, band_h, illum, hl_peak,
                                 hl_sx, hl_sy, hl_cx, hl_cy);
        }

        /* S5: geometry -- BEFORE the blur (the legacy path blurs first
         * and then rotates with nearest neighbour, which re-introduces
         * stair-stepping and is the wrong physical order). */
        if (rot != 0.0f) {
            uint8_t bgpix = (uint8_t)paper;
            rotate_gray(gray, band_w, band_h, (double)rot, (int)bgpix);
        }

        /* S6: optical blur (explicit sigma) + motion blur. */
        {
            float sigma = g_blur_sigma;
            if (sigma < 0.0f)
                sigma = (blur == 0) ? 0.0f : (blur == 1 ? 0.7f : 1.2f);
            if (sigma > 0.0f)
                mrz_phys_gauss_blur(gray, band_w, band_h, sigma);
        }
        if (g_motion_len >= 3 && mrz_phys_randf() < 0.2f)
            mrz_phys_motion_blur(gray, band_w, band_h, g_motion_len,
                                 g_motion_deg);

        /* S7: sensor noise (additive gaussian + dark current + salt&pepper). */
        {
            float salt = (noise > 0.0f) ? (float)noise : 0.0f;
            if (salt > 0.05f) salt = 0.05f;
            mrz_phys_sensor_noise(gray, band_w, band_h, g_noise_gauss, salt,
                                  seed ^ 0x9e3779b9u);
            if (g_dark_current > 0.0f) {
                /* §4.3: dark-current FPN amplitude <= 3/255 -- the option
                 * is therefore in 1/255 units, not a 0..1 fraction. */
                int dc = (int)g_dark_current;
                mrz_phys_srand(seed ^ 0x5bf03635u);
                for (int i = 0; i < band_w * band_h; ++i) {
                    int v = (int)gray[i] - dc;
                    if (v < 0) v = 0;
                    gray[i] = (uint8_t)v;
                }
            }
        }

        /* S8: downsample (bilinear, filter=true).  The gray buffer AND
         * the output image must shrink together: the RGB conversion below
         * walks band_w*band_h pixels and face_image_save_ppm writes
         * img->width x img->height -- leaving them out of sync wrote the
         * downscaled content into the top-left corner of an
         * original-size PPM and left the rest as uninitialized memory
         * (measured: a whole corpus with a black lower half).
         * The JPEG half of S8 is applied by gen_corpus.py (PIL round
         * trip) -- this binary has no libjpeg. */
        if (g_downscale < 0.999f) {
            mrz_phys_downsample(gray, &band_w, &band_h, g_downscale);
            img->width = band_w;
            img->height = band_h;
        }
    } else {
    for (int li = 0; li < n_lines; ++li) {
        const char *line = (li == 0) ? l1 : l2;
        int len = (int)strlen(line);
        int row_y = margin + li * (line_h + vgap);
        int row_x_start = margin;
        for (int i = 0; i < len; ++i) {
            int skew_dx = skew * i / len;
            int x = row_x_start + i * (glyph_w + hgap) + skew_dx;
            draw_glyph(gray, band_w, band_h, x, row_y, line[i], scale, invert);
        }
    }
    /* Defocus / anti-aliased strokes. */
    for (int p = 0; p < blur; ++p) blur3(gray, band_w, band_h);
    /* Real scanner tilt. */
    if (rot != 0.0f) rotate_gray(gray, band_w, band_h, (double)rot, bg);
    /* Add noise (deterministic when noise-seed is given — required for
     * reproducible corpora and regression baselines). */
    if (noise > 0) {
        if (noise_seed >= 0)
            srand((unsigned)noise_seed);
        else
            srand((unsigned)(time(NULL) ^ getpid()));
        for (int i = 0; i < band_w * band_h; ++i) {
            float r = (float)rand() / (float)RAND_MAX;
            if (r < noise) {
                /* Flip with 50% probability. */
                int flip = (rand() & 1);
                gray[i] = flip ? 0 : 255;
            }
        }
    }
    }   /* end of the legacy (phys=0) rendering branch */

    /* Convert grayscale back to RGB. */
    for (int i = 0; i < band_w * band_h; ++i) {
        img->pixels[i*3 + 0] = gray[i];
        img->pixels[i*3 + 1] = gray[i];
        img->pixels[i*3 + 2] = gray[i];
    }
    free(gray);
    if (face_image_save_ppm(img, out) != 0) {
        face_image_free(img);
        return 2;
    }
    face_image_free(img);
    fprintf(stderr, "wrote %s (%dx%d, scale=%d)\n", out, band_w, band_h, scale);
    return 0;
}
