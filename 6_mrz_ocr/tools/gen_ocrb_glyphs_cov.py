#!/usr/bin/env python3
"""Emit the 8-bit OCR-B glyph COVERAGE bank (tools/ocrb_glyphs_aa.h).

Training outline §4.1 asks for **font-level antialiasing**: the corpus
must carry real grey levels at the stroke edges.  The 1-bit bank
(tools/ocrb_glyphs.h) is thresholded at INK_THRESHOLD=128, so the only
grey it can produce is the 16-level fringe a blur3 leaves behind -- the
corpus stays quasi-binary (measured: 84% of the pixels are pure 0/255,
12 grey levels in the whole image).

This tool renders every glyph at 4x from the real OCR-B TrueType face and
box-downsamples it to the 8x12 cell, so every pixel carries its true ink
coverage 0..255.  The renderer then draws the glyph with a real ink
colour (20..110) blended by that coverage, which is what a camera sees
on a printed MRZ.

Kept as a separate tool from gen_ocrb_glyphs.py so the 1-bit path (and
every corpus already generated with it) stays bit-identical.

Usage:  python3 tools/gen_ocrb_glyphs_cov.py
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "tools"

CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ<"
CELL_W = 8
CELL_H = 12
FONT_SIZE = 13
BASELINE = 10
SS = 4

FONT_CANDIDATES = [
    ROOT.parent / "14_ultimateMRZ-SDK" / "assets" / "fonts" / "OcrB Regular.ttf",
    Path("/Library/Fonts/ocrb.ttf"),
    Path("/Library/Fonts/OCR-B.ttf"),
]


def pick_font() -> Path:
    for p in FONT_CANDIDATES:
        if p.exists():
            try:
                ImageFont.truetype(str(p), FONT_SIZE)
                return p
            except Exception:
                continue
    raise SystemExit("no usable OCR-B font found")


def coverage_cell(font: ImageFont.FreeTypeFont, ch: str) -> list[list[int]]:
    big = Image.new("L", (CELL_W * SS, CELL_H * SS), 255)
    ImageDraw.Draw(big).text((0, BASELINE * SS), ch, font=font, fill=0,
                              anchor="ls")
    small = big.resize((CELL_W, CELL_H), Image.BOX)
    px = small.load()
    return [[255 - px[x, y] for x in range(CELL_W)] for y in range(CELL_H)]


def main() -> int:
    font_path = pick_font()
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()[:16]
    font = ImageFont.truetype(str(font_path), FONT_SIZE * SS)
    bank = {}
    for ch in CHARS:
        cov = coverage_cell(font, ch)
        ink = sum(sum(r) for r in cov) / 255.0
        if not (4 <= ink <= 46):
            raise SystemExit(f"glyph {ch!r} looks broken (ink={ink:.1f} px)")
        bank[ch] = cov

    q = chr(39)
    lines = [
        "/* OCR-B glyph COVERAGE bank (8-bit) -- GENERATED by",
        " * tools/gen_ocrb_glyphs_cov.py.  Do not edit by hand.",
        " *",
        " * 8x12 cells with per-pixel ink coverage 0..255, rendered from a",
        " * real OCR-B TrueType face at 4x and box-downsampled.  This is the",
        " * font-level antialiasing the training outline §4.1 asks for: the",
        " * 1-bit bank (ocrb_glyphs.h) can only produce a 16-level fringe",
        " * after blur3, while this bank carries real stroke-edge tone.",
        " *",
        f" * font : {font_path}",
        f" * size : {FONT_SIZE}px, baseline row {BASELINE}",
        f" * sha256: {digest}",
        " */",
        "#ifndef MRZ_OCRB_GLYPHS_AA_H",
        "#define MRZ_OCRB_GLYPHS_AA_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct { char ch; uint8_t cov[12][8]; } mrz_ocr_ocrb_cov_t;",
        "",
        "static const mrz_ocr_ocrb_cov_t MRZ_OCRB_COV[] = {",
    ]
    for ch in CHARS:
        rows = []
        for y in range(CELL_H):
            rows.append("{" + ",".join(str(v) for v in bank[ch][y]) + "}")
        lines.append("    { " + q + ch + q + ", { " + ",".join(rows) + " } },")
    lines += ["};", "", "#endif /* MRZ_OCRB_GLYPHS_AA_H */", ""]
    out = TOOLS / "ocrb_glyphs_aa.h"
    out.write_text("\n".join(lines))
    print(f"font {font_path} (sha256:{digest})")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
