#!/usr/bin/env python3
"""Derive an 8x12 OCR-B glyph bank from a real OCR-B TrueType font.

The built-in bank in `src/template.c` is a hand-written *simplified* OCR-B
rendering: 2px blocky strokes, and several pairs (E/F, I/1, O/0, S/5) differ
in a single bit row.  That single-row difference is what makes the CNN
confuse E with F on low-resolution renders (see the `mrz_golden` scale=3
failure) and it means the synthetic corpora do not look like a scanned
machine-readable zone.

This tool renders the same 37 characters (A-Z, 0-9, '<') from a real OCR-B
TrueType face into the exact same 8x12 one-bit cell format, so every
downstream contract stays untouched:

  * cell geometry  : 8 columns x 12 rows, bit 7 = leftmost pixel
  * glyph order    : identical to MRZ_OCR_GLYPHS
  * consumers      : `tools/gen_mrz_image.c` (font=ocrb) and
                     `tools/train_cnn_v2.py` (MRZ_GLYPH_BANK=ocrb)

Outputs (both are generated, do not edit by hand):
  tools/ocrb_glyphs.h    C   : static const mrz_ocr_glyph_t bank
  tools/ocrb_glyphs.py   py  : GLYPHS = [(char, [rows...]), ...]

Usage:
  python3 tools/gen_ocrb_glyphs.py                 # write both outputs
  python3 tools/gen_ocrb_glyphs.py --preview       # ascii art only
  python3 tools/gen_ocrb_glyphs.py --font /path/to/ocrb.ttf
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "tools"

CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ<"
CELL_W = 8
CELL_H = 12

# Preferred font first: it ships with the repository, so the generated bank
# is reproducible on any machine.  The system OCR-B faces are fallbacks.
FONT_CANDIDATES = [
    ROOT.parent / "14_ultimateMRZ-SDK" / "assets" / "fonts" / "OcrB Regular.ttf",
    Path("/Library/Fonts/ocrb.ttf"),
    Path("/Library/Fonts/OCR-B.ttf"),
]

# Render size / baseline chosen so the caps fill ~10 of the 12 rows and the
# glyph stays inside the 8 column cell (no clipping, 1-2px strokes).
FONT_SIZE = 13
BASELINE = 10
INK_THRESHOLD = 128


def pick_font(explicit: str | None) -> Path:
    if explicit:
        p = Path(explicit)
        if not p.exists():
            raise SystemExit(f"font not found: {p}")
        return p
    for p in FONT_CANDIDATES:
        if p.exists():
            try:
                ImageFont.truetype(str(p), FONT_SIZE)
            except Exception:
                continue
            return p
    raise SystemExit("no usable OCR-B font found; pass --font")


def render_cell(font: ImageFont.FreeTypeFont, ch: str) -> list[int]:
    """Render one character into an 8x12 one-bit cell -> 12 row bytes."""
    img = Image.new("L", (CELL_W, CELL_H), 255)
    ImageDraw.Draw(img).text((0, BASELINE), ch, font=font, fill=0, anchor="ls")
    px = img.load()
    rows = []
    for y in range(CELL_H):
        bits = 0
        for x in range(CELL_W):
            if px[x, y] < INK_THRESHOLD:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def build_bank(font_path: Path) -> dict[str, list[int]]:
    font = ImageFont.truetype(str(font_path), FONT_SIZE)
    bank: dict[str, list[int]] = {}
    for ch in CHARS:
        rows = render_cell(font, ch)
        ink = sum(bin(r).count("1") for r in rows)
        if not (6 <= ink <= 44):
            raise SystemExit(f"glyph {ch!r} looks broken (ink={ink} px)")
        bank[ch] = rows
    return bank


def write_c_header(bank: dict[str, list[int]], font_path: Path, digest: str) -> Path:
    out = TOOLS / "ocrb_glyphs.h"
    lines = [
        "/* OCR-B glyph bank for MRZ -- GENERATED by tools/gen_ocrb_glyphs.py.",
        " *",
        " * 8x12 one-bit cells rendered from a real OCR-B TrueType face, so the",
        " * synthetic corpora carry the actual ICAO 9303 OCR-B character forms",
        " * instead of the hand-simplified shapes in src/template.c.",
        " *",
        f" * font : {font_path}",
        f" * size : {FONT_SIZE}px, baseline row {BASELINE}, threshold {INK_THRESHOLD}",
        f" * sha256: {digest}",
        " *",
        " * Do not edit by hand -- run: python3 tools/gen_ocrb_glyphs.py",
        " */",
        "#ifndef MRZ_OCRB_GLYPHS_H",
        "#define MRZ_OCRB_GLYPHS_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    char     ch;",
        "    uint8_t  rows[12]; /* bit 7 = leftmost pixel */",
        "} mrz_ocr_ocrb_glyph_t;",
        "",
        "static const mrz_ocr_ocrb_glyph_t MRZ_OCRB_GLYPHS[37] = {",
    ]
    for ch in CHARS:
        rows = ", ".join(f"0x{r:02X}" for r in bank[ch])
        lines.append(f"    {{'{ch}', {{{rows}}}}},")
    lines += [
        "};",
        "",
        "#endif /* MRZ_OCRB_GLYPHS_H */",
        "",
    ]
    out.write_text("\n".join(lines))
    return out


def write_py(bank: dict[str, list[int]], font_path: Path, digest: str) -> Path:
    out = TOOLS / "ocrb_glyphs.py"
    lines = [
        '"""OCR-B glyph bank -- GENERATED by tools/gen_ocrb_glyphs.py.',
        "",
        "8x12 one-bit cells rendered from a real OCR-B TrueType face.",
        f"font: {font_path}",
        f"sha256: {digest}",
        "",
        'Do not edit by hand -- run: python3 tools/gen_ocrb_glyphs.py',
        '"""',
        "",
        "GLYPHS = [",
    ]
    for ch in CHARS:
        rows = ", ".join(f"0x{r:02X}" for r in bank[ch])
        lines.append(f"    ('{ch}', [{rows}]),")
    lines += [
        "]",
        "",
        "GLYPH_INDEX = {c: i for i, (c, _) in enumerate(GLYPHS)}",
        "",
    ]
    out.write_text("\n".join(lines))
    return out


def preview(bank: dict[str, list[int]]) -> None:
    for i in range(0, len(CHARS), 6):
        grp = CHARS[i:i + 6]
        print("  ".join(grp))
        for y in range(CELL_H):
            print("  ".join(
                "".join("#" if bank[c][y] & (0x80 >> x) else "." for x in range(CELL_W))
                for c in grp))
        print()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", help="OCR-B TrueType path")
    ap.add_argument("--coverage", action="store_true",
                    help="also emit the 8-bit coverage bank "
                         "(tools/ocrb_glyphs_aa.h) for the §4.1 font-level "
                         "antialiasing path")
    ap.add_argument("--preview", action="store_true", help="ascii art only")
    a = ap.parse_args()

    font_path = pick_font(a.font)
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()[:16]
    bank = build_bank(font_path)

    if a.preview:
        preview(bank)
        return 0

    c_out = write_c_header(bank, font_path, digest)
    py_out = write_py(bank, font_path, digest)
    print(f"font {font_path} (sha256:{digest})")
    print(f"wrote {c_out}")
    print(f"wrote {py_out}")
    preview(bank)
    return 0


if __name__ == "__main__":
    sys.exit(main())
